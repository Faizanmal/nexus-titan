def ref_name(schema: dict) -> str | None:
    ref = schema.get("$ref", "")
    return ref.rsplit("/", 1)[-1] if ref else None


def ts_type(schema: dict) -> str:
    if isinstance(schema.get("type"), list):
        return " | ".join(
            "null" if item == "null" else ts_type({**schema, "type": item})
            for item in schema["type"]
        )
    if name := ref_name(schema):
        return name
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    kind = schema.get("type")
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "array":
        item = ts_type(schema.get("items", {}))
        return f"Array<{item}>"
    if kind == "object":
        props = schema.get("properties", {})
        if not props:
            return "Record<string, unknown>"
        required = set(schema.get("required", []))
        rows = [
            f"  {key}{'' if key in required else '?'}: {ts_type(value)};"
            for key, value in props.items()
        ]
        return "{\n" + "\n".join(rows) + "\n}"
    return "unknown"


def py_type(schema: dict) -> str:
    if isinstance(schema.get("type"), list):
        return " | ".join(
            "None" if item == "null" else py_type({**schema, "type": item})
            for item in schema["type"]
        )
    if name := ref_name(schema):
        return "Vector3" if name == "Vector3" else name
    if "const" in schema or "enum" in schema:
        choices = schema.get("enum", [schema.get("const")])
        return "Literal[" + ", ".join(repr(choice) for choice in choices) + "]"
    kind = schema.get("type")
    if kind == "string":
        return "str"
    if kind == "integer":
        return "int"
    if kind == "number":
        return "float"
    if kind == "boolean":
        return "bool"
    if kind == "array":
        return f"list[{py_type(schema.get('items', {}))}]"
    if kind == "object":
        return "dict[str, Any]"
    return "Any"


def make_python(defs: dict) -> str:
    out = [
        '"""Generated by scripts/generate-contracts.py; do not edit."""',
        "from __future__ import annotations",
        "from typing import Any, Literal, NotRequired, TypedDict",
        f'SCHEMA_VERSION: Literal["{VERSION}"] = "{VERSION}"',
        "Vector3 = list[float]",
        "",
    ]
    for name, schema in defs.items():
        if schema.get("type") != "object":
            if "enum" in schema:
                values = ", ".join(repr(value) for value in schema["enum"])
                out.append(f"{name} = Literal[{values}]")
                out.append("")
            elif name != "Vector3":
                out.append(f"{name} = {py_type(schema)}")
                out.append("")
            continue
        required = set(schema.get("required", []))
        out.append(f"class {name}(TypedDict):")
        properties = schema.get("properties", {})
        if not properties:
            out.append("    pass")
        for field, prop in properties.items():
            typ = py_type(prop)
            if field not in required:
                typ = f"NotRequired[{typ}]"
            out.append(f"    {field}: {typ}")
        out.append("")
    return "\n".join(out)


def make_typescript(defs: dict) -> str:
    chunks = [
        "/* Generated by scripts/generate-contracts.py; do not edit. */",
        f'export const SCHEMA_VERSION = "{VERSION}" as const;\n',
    ]
    for name, schema in defs.items():
        if schema.get("type") == "object":
            rows = []
            required = set(schema.get("required", []))
            for key, value in schema.get("properties", {}).items():
                rows.append(
                    f"  {key}{'' if key in required else '?'}: {ts_type(value)};"
                )
            chunks.append(f"export interface {name} {{\n" + "\n".join(rows) + "\n}\n")
        else:
            chunks.append(f"export type {name} = {ts_type(schema)};\n")
    for name in (
        "SchemaVersion",
        "DataClassification",
        "EventSource",
        "RiskTier",
        "PolicyOutcome",
        "SimulationStatus",
        "ErrorCode",
    ):
        values = json.dumps(defs[name]["enum"])
        chunks.append(
            f"export const {name}Values = {values} as const;\n"
            f"export const is{name} = (value: unknown): value is {name} => "
            f"typeof value === 'string' && ({name}Values as readonly string[]).includes(value);\n"
        )
    return "\n".join(chunks)


def kotlin_type(schema: dict) -> str:
    if isinstance(schema.get("type"), list):
        concrete = next((item for item in schema["type"] if item != "null"), None)
        return (
            f"{kotlin_type({**schema, 'type': concrete})}?"
            if concrete
            else "JsonElement?"
        )
    if name := ref_name(schema):
        return "List<Double>" if name == "Vector3" else name
    if "const" in schema or "enum" in schema or schema.get("type") == "string":
        return "String"
    if schema.get("type") in ("integer", "number"):
        return "Long" if schema["type"] == "integer" else "Double"
    if schema.get("type") == "boolean":
        return "Boolean"
    if schema.get("type") == "array":
        return f"List<{kotlin_type(schema.get('items', {}))}>"
    if schema.get("type") == "object":
        return "Map<String, JsonElement>"
    return "JsonElement"


def swift_type(schema: dict) -> str:
    if isinstance(schema.get("type"), list):
        concrete = next((item for item in schema["type"] if item != "null"), None)
        return (
            f"{swift_type({**schema, 'type': concrete})}?" if concrete else "JSONValue?"
        )
    if name := ref_name(schema):
        return "[Double]" if name == "Vector3" else name
    if "const" in schema or "enum" in schema or schema.get("type") == "string":
        return "String"
    if schema.get("type") in ("integer", "number"):
        return "Int" if schema["type"] == "integer" else "Double"
    if schema.get("type") == "boolean":
        return "Bool"
    if schema.get("type") == "array":
        return f"[{swift_type(schema.get('items', {}))}]"
    if schema.get("type") == "object":
        return "[String: JSONValue]"
    return "JSONValue"


def swift_name(value: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "_", value).upper()


def swift_case(value: str) -> str:
    case = re.sub(r"[^A-Za-z0-9]", "_", value).lower()
    if case[0].isdigit():
        case = "v_" + case
    return (
        f"{case}Value"
        if case
        in {"public", "internal", "private", "fileprivate", "open", "case", "default"}
        else case
    )


def kotlin_case(value: str) -> str:
    case = swift_name(value)
    return "V_" + case if case[0].isdigit() else case


def make_swift(defs: dict) -> str:
    out = [
        "// Generated by scripts/generate-contracts.py; do not edit.",
        "import Foundation",
        f'public let nexusSchemaVersion = "{VERSION}"',
        "",
        "// Raw-value decoding rejects unknown enum strings with DecodingError.",
    ]
    for name, schema in defs.items():
        if "enum" in schema:
            cases = [
                f'    case {swift_case(value)} = "{value}"' for value in schema["enum"]
            ]
            out.extend(
                [f"public enum {name}: String, Codable, Sendable {{", *cases, "}", ""]
            )
    out.extend(
        [
            "public enum JSONValue: Codable, Sendable {",
            "    case string(String), number(Double), bool(Bool), object([String: JSONValue]), array([JSONValue]), null",
            "    public init(from decoder: Decoder) throws {",
            "        let c = try decoder.singleValueContainer()",
            "        if c.decodeNil() { self = .null }",
            "        else if let v = try? c.decode(Bool.self) { self = .bool(v) }",
            "        else if let v = try? c.decode(Double.self) { self = .number(v) }",
            "        else if let v = try? c.decode(String.self) { self = .string(v) }",
            "        else if let v = try? c.decode([JSONValue].self) { self = .array(v) }",
            "        else { self = .object(try c.decode([String: JSONValue].self)) }",
            "    }",
            "    public func encode(to encoder: Encoder) throws {",
            "        var c = encoder.singleValueContainer()",
            "        switch self { case .string(let v): try c.encode(v); case .number(let v): try c.encode(v); case .bool(let v): try c.encode(v); case .object(let v): try c.encode(v); case .array(let v): try c.encode(v); case .null: try c.encodeNil() }",
            "    }",
            "}",
            "",
        ]
    )
    for name, schema in defs.items():
        if schema.get("type") != "object":
            continue
        required = set(schema.get("required", []))
        out.append(f"public struct {name}: Codable, Sendable {{")
        for field, prop in schema.get("properties", {}).items():
            typ = swift_type(prop)
            if field not in required and not typ.endswith("?"):
                typ += "?"
            out.append(f"    public let {field}: {typ}")
        params = []
        for field, prop in schema.get("properties", {}).items():
            typ = swift_type(prop)
            if field in required:
                params.append(f"{field}: {typ}")
            else:
                params.append(
                    f"{field}: {typ if typ.endswith('?') else typ + '?'} = nil"
                )
        out.append("    public init(" + ", ".join(params) + ") {")
        for field in schema.get("properties", {}):
            out.append(f"        self.{field} = {field}")
        out.extend(["    }", ""])
        out.append("}")
        out.append("")
    out.extend(
        [
            "public enum ContractValidationError: Error { case duplicateEventID(String), invalidVectorLength }",
            "public extension EventBatch {",
            "    func validate() throws {",
            "        let ids = events.map(\\.event_id)",
            '        guard Set(ids).count == ids.count else { throw ContractValidationError.duplicateEventID("batch") }',
            "    }",
            "}",
            "public func validateVector3(_ value: [Double]) throws {",
            "    guard value.count == 3 else { throw ContractValidationError.invalidVectorLength }",
            "}",
            "",
        ]
    )
    return "\n".join(out)


def make_kotlin(defs: dict) -> str:
    out = [
        "// Generated by scripts/generate-contracts.py; do not edit.",
        "package dev.nexustitan.contracts",
        "",
        "import kotlinx.serialization.SerialName",
        "import kotlinx.serialization.Serializable",
        "import kotlinx.serialization.json.JsonElement",
        f'public const val NEXUS_SCHEMA_VERSION: String = "{VERSION}"',
        "",
        "// kotlinx.serialization rejects unknown enum strings with SerializationException.",
    ]
    for name, schema in defs.items():
        if "enum" in schema:
            out.append("@Serializable")
            out.append(f"public enum class {name} {{")
            cases = [
                f'    @SerialName("{value}") {kotlin_case(value)}'
                for value in schema["enum"]
            ]
            out.append(",\n".join(cases))
            out.extend(["}", ""])
    for name, schema in defs.items():
        if name == "Vector3":
            out.append("public typealias Vector3 = List<Double>")
            out.append("")
            continue
        if schema.get("type") != "object":
            continue
        required = set(schema.get("required", []))
        out.append("@Serializable")
        out.append(f"public data class {name}(")
        rows = []
        for field, prop in schema.get("properties", {}).items():
            typ = kotlin_type(prop)
            if field not in required:
                typ += " = null" if typ.endswith("?") else "? = null"
            rows.append(f'    @SerialName("{field}") val {field}: {typ}')
        out.append(",\n".join(rows))
        out.extend([")", ""])
    out.extend(
        [
            "public fun EventBatch.validate() {",
            '    require(events.map { it.event_id }.toSet().size == events.size) { "duplicate event_id in batch" }',
            "}",
            'public fun validateVector3(value: Vector3) { require(value.size == 3) { "vector must have exactly three coordinates" } }',
            "",
        ]
    )
    return "\n".join(out)


