def rewrite_refs(value):
    if isinstance(value, dict):
        if "$ref" in value and value["$ref"].startswith("#/$defs/"):
            value["$ref"] = value["$ref"].replace("#/$defs/", "#/components/schemas/")
        for item in value.values():
            rewrite_refs(item)
    elif isinstance(value, list):
        for item in value:
            rewrite_refs(item)


def outputs() -> dict[Path, str]:
    root_schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    defs = root_schema["$defs"]
    return {
        ROOT / "docs/api/openapi.json": make_openapi(defs),
        ROOT / "packages/contracts/src/generated.ts": make_typescript(defs),
        ROOT
        / "bindings/swift/Sources/NexusTitanContracts/GeneratedContracts.swift": make_swift(
            defs
        ),
        ROOT
        / "bindings/kotlin/src/main/kotlin/dev/nexustitan/contracts/GeneratedContracts.kt": make_kotlin(
            defs
        ),
        ROOT
        / "services/api/src/nexus_titan_api/generated_contracts.py": make_python(defs),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check", action="store_true", help="fail if generated outputs are stale"
    )
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
            print(f"generated {path.relative_to(ROOT).as_posix()}")
    if stale:
        print("stale generated contracts: " + ", ".join(stale), file=sys.stderr)
        return 1
    if args.check:
        print("contract codegen is current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
